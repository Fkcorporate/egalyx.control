"""
egalyx/guide_illustre.py — guide illustré pas à pas du centre d'aide.

Chaque guide est une fiche du centre d'aide (même recherche, mêmes droits, même assistant) qui porte en plus
des « illustrations » : une capture d'écran de l'outil, annotée de repères rouges numérotés, et la légende
de chaque repère dans le même ordre (repère 1 = premier élément de la liste « reperes »).

Les images sont dans static/aide/guide/ (WebP). Elles ont été prises sur une organisation de démonstration
fictive (« Banque Horizon ») : aucune donnée client.

Pour ajouter une capture : déposer l'image dans static/aide/guide/ puis ajouter un I(...) au guide concerné.
"""

DOSSIER = 'aide/guide/'          # sous /static
CATEGORIE = ('guide', 'Guide illustré pas à pas', 'fa-images')


def I(image, titre, texte='', reperes=()):
    """Une capture : image (nom du fichier), titre de l'étape, texte d'explication, légendes des repères 1, 2, 3…"""
    return {'image': DOSSIER + image, 'titre': titre, 'texte': texte, 'reperes': list(reperes)}


def G(id, titre, resume, illustrations, notes=(), mots=(), liens=(), perms=None, pour='tous', questions=()):
    etapes = [f"**{x['titre']}** — {x['texte']}" if x['texte'] else f"**{x['titre']}**" for x in illustrations]
    return {'id': id, 'cat': CATEGORIE[0], 'titre': titre, 'resume': resume, 'etapes': etapes,
            'notes': list(notes), 'mots': ['guide', 'illustre', 'capture', 'ecran', 'pas a pas', 'tutoriel', 'image']
            + list(mots), 'liens': list(liens), 'perms': tuple(perms) if perms else None, 'pour': pour,
            'questions': list(questions), 'illustrations': illustrations}


