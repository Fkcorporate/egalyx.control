def installer(articles, categories):
    """Ajoute la catégorie (en tête) et les guides à la base de connaissances, une seule fois."""
    if not any(c[0] == CATEGORIE[0] for c in categories):
        categories.insert(0, CATEGORIE)
    deja = {a['id'] for a in articles}
    articles.extend(g for g in GUIDES if g['id'] not in deja)
